def renderizar_pagina_experience():
    page_header(
        "Experience - Batalha de Equipes",
        icon=":material/groups:",
    )

    if st.button("🔄 Atualizar Dados"):
        clear_loader_cache(carregar_experience_page, "carregar_experience_page")
        clear_loader_cache(carregar_experience_page_dia, "carregar_experience_page_dia")
        st.session_state["_experience_ready"] = True
        st.rerun()
    force = st.session_state.pop("_experience_ready", False)
    df = load_if_cache_ready(
        carregar_experience_page,
        "carregar_experience_page",
        "experience_page",
        force=force,
    )
    df_dia = load_if_cache_ready(
        carregar_experience_page_dia,
        "carregar_experience_page_dia",
        "experience_page_dia",
        force=force,
    )
    if df is None or df_dia is None:
        st.info("Os dados ainda não estão no cache. Aguarde o aquecimento ou clique em 'Atualizar Dados'.")
        return

    if df is not None and not df.empty:
        col1, col2, col3, col4 = st.columns(4)
        with col1:
            fornecedores = sorted(df['Fornecedor'].dropna().unique())
            fornecedor_opcoes = ["Todos"] + fornecedores
            fornecedor_selecionado = st.selectbox(
                "Fornecedor",
                options=fornecedor_opcoes,
                index=0,
                key="fornecedor_select"
            )

        # Filtra vendas do mês
        if fornecedor_selecionado != "Todos":
            df_filtrado = df[df['Fornecedor'] == fornecedor_selecionado]
        else:
            df_filtrado = df

        df_agg = (
            df_filtrado
            .groupby(['SUPERVISOR', 'Vendedor'], as_index=False)['VALOR']
            .sum()
        )

        df_metas = carregar_metas()

        # Prepara metas conforme o filtro de fornecedor
        if fornecedor_selecionado != "Todos":
            df_meta_filtrada = df_metas[df_metas['Fornecedor'] == fornecedor_selecionado][['SUPERVISOR', 'Vendedor', 'META']].copy()
        else:
            df_meta_filtrada = df_metas.groupby(['SUPERVISOR', 'Vendedor'], as_index=False)['META'].sum()

        # Normaliza chaves para merge
        df_meta_filtrada['key_sup'] = df_meta_filtrada['SUPERVISOR'].apply(normalizar)
        df_meta_filtrada['key_vend'] = df_meta_filtrada['Vendedor'].apply(normalizar)

        df_agg['key_sup'] = df_agg['SUPERVISOR'].apply(normalizar)
        df_agg['key_vend'] = df_agg['Vendedor'].apply(normalizar)

        df_completo = df_meta_filtrada.merge(
            df_agg[['key_sup', 'key_vend', 'VALOR']],
            on=['key_sup', 'key_vend'],
            how='left'
        )
        df_completo['VALOR'] = df_completo['VALOR'].fillna(0)

        # Calcula % atingido
        df_completo['% Atingido'] = np.where(
            df_completo['META'] > 0,
            (df_completo['VALOR'] / df_completo['META']) * 100,
            0
        )

        # --- Prepara dados do dia ---
        if df_dia is not None and not df_dia.empty:
            # Normaliza vendedor nos dados do dia
            df_dia['key_vend'] = df_dia['Vendedor'].apply(normalizar)
            # Filtra pelo fornecedor selecionado
            if fornecedor_selecionado != "Todos":
                df_dia_filtrado = df_dia[df_dia['Fornecedor'] == fornecedor_selecionado]
            else:
                df_dia_filtrado = df_dia
            # Agrega valor do dia por vendedor
            df_dia_agg = df_dia_filtrado.groupby('key_vend')['Valor_Dia'].sum().reset_index()
        else:
            df_dia_agg = pd.DataFrame(columns=['key_vend', 'Valor_Dia'])

        # Merge com dados completos
        df_completo = df_completo.merge(df_dia_agg, on='key_vend', how='left')
        df_completo['Valor_Dia'] = df_completo['Valor_Dia'].fillna(0)

        # Remove colunas auxiliares
        df_completo = df_completo.drop(columns=['key_sup', 'key_vend'])

        # Ordena supervisores pelo VALOR total
        supervisores_ordenados = (
            df_completo.groupby('SUPERVISOR')['VALOR']
            .sum()
            .sort_values(ascending=False)
            .index
            .tolist()
        )

        # Exibe grid 2x2
        for i in range(0, len(supervisores_ordenados), 2):
            cols = st.columns(2)
            for j in range(2):
                idx = i + j
                if idx < len(supervisores_ordenados):
                    sup = supervisores_ordenados[idx]
                    df_sup = df_completo[df_completo['SUPERVISOR'] == sup]
                    total_sup = df_sup['VALOR'].sum()

                    with cols[j]:
                        with st.expander(f"👤 {sup}  |  TOTAL: {formata_real(total_sup)}", expanded=True):
                            # Seleciona e ordena colunas conforme solicitado
                            df_vend = df_sup[['Vendedor', 'META', 'VALOR', '% Atingido', 'Valor_Dia']].copy()
                            df_vend = df_vend.sort_values('VALOR', ascending=False).reset_index(drop=True)
                            df_vend = df_vend.rename(columns={
                                'VALOR': 'Valor Total',
                                'META': 'Meta',
                                'Valor_Dia': 'Valor do Dia'
                            })

                            # Formatação e barra
                            styled_df = df_vend.style.format({
                                'Meta': formata_real,
                                'Valor Total': formata_real,
                                '% Atingido': '{:.1f}%',
                                'Valor do Dia': formata_real
                            }).bar(subset=['% Atingido'], color='#4caf50', vmin=0, vmax=100)

                            st.dataframe(
                                styled_df,
                                hide_index=True,
                                width="stretch",
                                alt=f"Metas e vendas por vendedor do supervisor {sup}",
                            )

        st.caption(f"Exibindo {len(df_completo)} vendedores com metas.")

    else:
        st.warning("Nenhum dado encontrado ou ocorreu um erro na consulta.")

if __name__ == "__main__":
    renderizar_pagina_experience()